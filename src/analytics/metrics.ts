export const METRIC_BY_NAME: Record<string, MetricSpec> = Object.fromEntries(
  METRICS.map((metric) => [metric.metric_name, metric]),
);

export function getMetric(name: string): MetricSpec {
  const metric = METRIC_BY_NAME[name];
  if (!metric) throw new Error(`Unknown metric: ${name}`);
  return metric;
}

/** Evaluate a governed metric. The ONLY entry point for a metric value. */
export function evaluateMetric(
  name: string,
  mart: AnalyticsMart,
  filters: ResolvedFilters,
): number {
  const metric = getMetric(name);
  const rows = applyFilters(metric.select(mart), filters);
  return metric.compute(rows, mart, filters);
}

/** Metric definitions without their compute closures — safe to serialise. */
export function metricCatalog(): MetricDefinition[] {
  return METRICS.map(({ select: _select, compute: _compute, ...definition }) => definition);
}
